print("Здравстуйте, введите целое число от 1 до 25:")#условие
n=int(input())#вводим число
v=0#задаем значение
if n>=1 and n<=25:#условие работы программы
    for p in range(2,n):#задаем
        if n % p==0: #проверяем остаток от числа 
            v+=1
    if n>=2 and v==0:
        print("Y")
    else:
        print("N")
else:
    print("ошибка, введите целое число от 1 до 25")       